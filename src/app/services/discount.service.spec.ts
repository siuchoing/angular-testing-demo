import { DiscountService } from './discount.service';
// =========================================================================
// 📘 describe：測試套件 (Test Suite)
// 作用：將性質相近的測試案例「群組化」。
// 格式：describe('被測試的目標名稱/情境', () => { 裡面放多個 it });
// =========================================================================
describe('DiscountService 單元測試', () => {

  // =======================================================================
  // 📝 it：測試案例 (Test Case)
  // 作用：定義一個具體的「測試規格」或「預期行為」，是實際執行斷言(Expect)的地方。
  // 格式：it('應該達成的預期結果 (以動詞開頭)', () => { 實際測試邏輯 });
  // 💡 註：在很多框架中，it() 和 test() 是完全等價的。
  // =======================================================================
  it('應該正確計算滿千折百', () => {
    // 💡 像一般 JS 一樣直接 new 類別，速度極快，完全隔離外部環境
    const service = new DiscountService(); 
    
    const result = service.applyCoupon(1000, 'MINUS_100');
    
    // 驗證數學邏輯是否正確
    expect(result).toBe(900); 
  });
});